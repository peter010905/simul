from pathlib import Path
import json,math
import numpy as np
import rosbag2_py as bag
from rclpy.serialization import deserialize_message
from rosidl_runtime_py.utilities import get_message
from osp_mission.r32_drive import grid_from_message
from osp_mission._r32_navigation_core import Grid,connected_nav_cells
from osp_mission.box_access import box_routes
from osp_mission.wall_lap import WallLap,measured_perimeter
from osp_mission.center_wall import CenterWall

import argparse
parser=argparse.ArgumentParser(description='Replay failed initial wall entry from recorded SLAM and costmaps.')
parser.add_argument('run',type=Path)
parser.add_argument('--inputs',type=Path,default=Path('/tmp/lap47-inputs'))
args=parser.parse_args()
p=args.run
start=next(r['wall_epoch_s'] for r in map(json.loads,(p/'artifacts/startup.jsonl').read_text().splitlines()) if r['event']=='mission_started')
reader=bag.SequentialReader();reader.open(bag.StorageOptions(uri=str(p/'rosbag'),storage_id='mcap'),bag.ConverterOptions('',''))
wanted={'/tf','/odom','/global_costmap/costmap','/local_costmap/costmap'}
types={t.name:get_message(t.type) for t in reader.get_all_topics_and_types() if t.name in wanted};reader.set_filter(bag.StorageFilter(topics=list(types)))
def stream():
 while reader.has_next():
  n,r,t=reader.read_next();yield n,deserialize_message(r,types[n]),t/1e9-start
it=iter(stream());msg=next(it,None);costs={};odom=None;transform=None
lap=WallLap();results=[]
for f in sorted((p/'artifacts/policy_decisions').glob('*npz'))[:7]:
 a=np.load(f);elapsed=float(a['elapsed'])
 while msg and msg[2]<=elapsed:
  name,m,t=msg
  if name=='/tf':
   for tr in m.transforms:
    if (tr.header.frame_id,tr.child_frame_id)==('map','odom'):
     q=tr.transform.rotation;h=math.atan2(2*(q.w*q.z+q.x*q.y),1-2*(q.y*q.y+q.z*q.z));c,s=math.cos(h),math.sin(h);x,y=tr.transform.translation.x,tr.transform.translation.y
     transform=(-c*x-s*y,s*x-c*y,-h)
  elif name=='/odom':
   q=m.pose.pose.orientation;odom=(t,m.pose.pose.position.x,m.pose.pose.position.y,math.atan2(2*(q.w*q.z+q.x*q.y),1-2*(q.y*q.y+q.z*q.z)))
  else:costs[name]=(m.header.frame_id,grid_from_message(m))
  msg=next(it,None)
 transform_source='tf'
 if transform is None and odom and abs(odom[0]-elapsed)<=.15:
  h=odom[3]-float(a['heading']);c,s=math.cos(h),math.sin(h);x,y=a['robot']
  transform=(odom[1]-c*x+s*y,odom[2]-s*x-c*y,h);transform_source='paired'
 if transform is None or '/global_costmap/costmap' not in costs:continue
 g=Grid(a['data'],float(a['resolution']),(*a['origin'],0.));cost=costs['/global_costmap/costmap'][1]
 pose=(*a['robot'],float(a['heading']))
 safe,_=g.reachable(pose[:2],.32)
 nav=connected_nav_cells(cost,pose)
 joint,dist=box_routes(g,cost,nav,safe,pose,transform,costs.get('/local_costmap/costmap'))
 goal=lap.choose(g,dist,pose,transform,elapsed,600.,lambda _:False)
 boundary=measured_perimeter(g,pose)
 row=dict(snapshot=f.name,elapsed=round(elapsed,2),safe_start=bool(joint[g.index(*pose[:2])]),
          connected=int(np.isfinite(dist).sum()),perimeter=lap.report(),goal=goal)
 if boundary is not None:
  pts,floor,supported,chairs=boundary
  row.update(boundary_cells=len(pts),supported_cells=int(supported.sum()))
  # Compare with independent wall observation positions already generated by the scheduler.
 c=CenterWall();captured=[]
 original=c.wall_lap.choose
 def capture(grid,d,pose,transform,t,duration,veto):
  return original(grid,d,pose,transform,t,duration,veto)
 c.wall_lap.choose=capture
 choices=[dict(x=x,y=y,yaw=yaw,scan_angle=scan,distance=d,features=np.array([v,fr,d,tu,re]))
          for x,y,yaw,scan,v,fr,d,tu,re in a['candidates']]
 selected=c.decide(g,cost,pose,transform,a['viewed'],elapsed,600.,lambda _:False,choices)
 row['full_selector_kind']=selected.get('r32_kind') if selected else None
 row['full_selector_reason']=c.reason
 row['wall_choices']=c.counts.get('wall')
 # Saved inputs permit repeated parent/candidate comparisons with identical masks.
 out=args.inputs;out.mkdir(exist_ok=True,parents=True)
 np.savez(out/f.name,data=a['data'],resolution=a['resolution'],origin=a['origin'],pose=pose,
          transform=transform,joint=joint,distances=dist,elapsed=elapsed)
 if goal:row['goal']={k:v for k,v in goal.items() if k!='features'}
 results.append(row)
 if transform_source=='paired':transform=None
print(json.dumps(results,indent=2))
